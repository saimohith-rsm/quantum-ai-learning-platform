def circuit_to_qasm(circuit: CircuitSchema) -> str:
    """Exports circuit into OpenQASM 2.0 / 3.0 compatible format."""
    lines = [
        'OPENQASM 2.0;',
        'include "qelib1.inc";',
        '',
        f'qreg q[{circuit.qubits}];',
        f'creg c[{circuit.qubits}];',
        ''
    ]

    sorted_gates = sorted(circuit.gates, key=lambda g: (g.step, g.target))

    for gate in sorted_gates:
        name = gate.name.upper()
        tgt = gate.target
        ctrl = gate.control
        ctrl2 = gate.control2
        params = gate.params or {}

        if name == "H":
            lines.append(f'h q[{tgt}];')
        elif name == "X":
            lines.append(f'x q[{tgt}];')
        elif name == "Y":
            lines.append(f'y q[{tgt}];')
        elif name == "Z":
            lines.append(f'z q[{tgt}];')
        elif name == "S":
            lines.append(f's q[{tgt}];')
        elif name in ("SDG", "S_DAG"):
            lines.append(f'sdg q[{tgt}];')
        elif name == "T":
            lines.append(f't q[{tgt}];')
        elif name in ("TDG", "T_DAG"):
            lines.append(f'tdg q[{tgt}];')
        elif name == "RX":
            theta = params.get("theta", 3.14159)
            lines.append(f'rx({theta}) q[{tgt}];')
        elif name == "RY":
            theta = params.get("theta", 3.14159)
            lines.append(f'ry({theta}) q[{tgt}];')
        elif name == "RZ":
            theta = params.get("theta", 3.14159)
            lines.append(f'rz({theta}) q[{tgt}];')
        elif name in ("CNOT", "CX"):
            lines.append(f'cx q[{ctrl}],q[{tgt}];')
        elif name == "CZ":
            lines.append(f'cz q[{ctrl}],q[{tgt}];')
        elif name == "SWAP":
            lines.append(f'swap q[{ctrl}],q[{tgt}];')
        elif name in ("CCX", "TOFFOLI"):
            lines.append(f'ccx q[{ctrl}],q[{ctrl2}],q[{tgt}];')
        elif name == "MEASURE":
            lines.append(f'measure q[{tgt}] -> c[{tgt}];')

    return "\n".join(lines)


def export_all_sdks(circuit: CircuitSchema) -> dict:
    """Returns a dictionary containing transpiled code across all supported quantum SDKs."""
    return {
        "qiskit": circuit_to_qiskit(circuit),
        "cirq": circuit_to_cirq(circuit),
        "pennylane": circuit_to_pennylane(circuit),
        "braket": circuit_to_braket(circuit),
        "qasm": circuit_to_qasm(circuit)
    }
